"""Postgres-mode building blocks that can be checked WITHOUT a Postgres server (pure functions + static scan).
The real database behaviour is covered by running the whole suite with TEST_PG_URL set (see conftest.py)."""
import ast
from pathlib import Path

import pytest

from app.core import db
from app.core.config import Settings
from app.services.sync import build_sync

APP = Path(__file__).resolve().parents[1] / "app"


def tr(sql, params=True):
    return db.translate(sql, params)[0]


def test_placeholders_percent_and_quotes():
    assert tr("SELECT * FROM t WHERE a = ? AND b = ?") == "SELECT * FROM t WHERE a = %s AND b = %s"
    assert tr("SELECT 1 WHERE a LIKE '50%' AND b = ?") == "SELECT 1 WHERE a ILIKE '50%%' AND b = %s"
    assert tr("SELECT '?' AS q, ?") == "SELECT '?' AS q, %s"  # a ? inside a string literal is not a placeholder
    assert tr("SELECT '50%' AS p", params=False) == "SELECT '50%' AS p"  # no params: psycopg does no % processing


def test_timestamp_like_rowid_and_insert_or_ignore():
    out = tr("UPDATE conversations SET updated_at = strftime('%Y-%m-%dT%H:%M:%fZ','now') WHERE id = ?")
    assert "strftime" not in out and "to_char(timezone('utc', now())" in out and out.endswith("id = %s")
    assert tr("SELECT * FROM c ORDER BY updated_at DESC, rowid DESC", False).endswith("ctid DESC")
    assert tr("SELECT * FROM n WHERE title LIKE ? ESCAPE '\\'") == "SELECT * FROM n WHERE title ILIKE %s ESCAPE '\\'"
    assert tr("INSERT OR IGNORE INTO skills(name) VALUES (?)") == "INSERT INTO skills(name) VALUES (%s) ON CONFLICT DO NOTHING"


def test_returning_id_only_for_autoincrement_tables():
    sql, ret = db.translate("INSERT INTO memories(kind, content) VALUES (?, ?)", True)
    assert ret and sql.endswith("RETURNING id")
    assert db.translate("INSERT INTO meta(key, value) VALUES (?, ?)", True)[1] is False  # meta has no id column
    assert db.translate("INSERT INTO conversations(id, title) VALUES (?, ?)", True)[1] is False  # text id, set by caller
    assert {"messages", "memories", "notes", "tasks", "audit_log", "agent_steps", "agent_approvals", "skill_versions"} == set(db.AUTOINC_TABLES)


def test_postgres_ddl_is_generated_from_the_sqlite_ddl_and_has_no_sqlite_isms():
    pg = db.pg_migrations()
    assert [n for n, _ in pg] == [n for n, _ in db.MIGRATIONS]
    blob = "".join(sql for _, sql in pg)
    assert "AUTOINCREMENT" not in blob and "strftime" not in blob
    assert blob.count("GENERATED BY DEFAULT AS IDENTITY") == len(db.AUTOINC_TABLES)  # BY DEFAULT: restore inserts explicit ids


def test_every_sql_string_in_the_app_survives_translation():
    """Static guard: no SQLite-only spelling may remain after translate(), so Postgres never sees it."""
    bad = ("strftime(", "AUTOINCREMENT", "INSERT OR ", "PRAGMA", "sqlite_", "rowid", " LIKE ")
    checked = 0
    for path in APP.rglob("*.py"):
        if path.name in ("db.py", "sync.py"):  # the dialect layer itself / SQLite-only snapshot code
            continue
        for node in ast.walk(ast.parse(path.read_text())):
            if isinstance(node, ast.Constant) and isinstance(node.value, str):
                text = node.value
                if not any(text.lstrip().upper().startswith(k) for k in ("SELECT ", "INSERT ", "UPDATE ", "DELETE FROM")):
                    continue
                out = tr(text)
                for token in bad:
                    assert token not in out, f"{path.name}: {token!r} survives translation in: {text[:80]}"
                checked += 1
    assert checked > 50  # the scan really looked at the app's SQL


def test_target_hides_password_and_settings_switch_backend():
    t = db.PgTarget("postgresql://user:hunter2@host.example/db?sslmode=require")
    assert "hunter2" not in repr(t) and "hunter2" not in str(t)
    s = Settings(_env_file=None, database_url="postgresql://user:hunter2@host.example/db")
    assert db.is_postgres(s.db_path) and db.engine_name(s.db_path) == "postgres" and "hunter2" not in repr(s)
    assert db.engine_name(Settings(_env_file=None).db_path) == "sqlite"  # default unchanged
    with pytest.raises(ValueError):
        db.PgTarget("postgresql://x", schema="bad; DROP")


